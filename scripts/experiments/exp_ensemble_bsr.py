#!/usr/bin/env python3
"""B1: Ensemble BSR experiment — cross-pi-class consensus lowers BSR.

Shows that the projection taxonomy is an ensemble design principle:
combining evaluators from different pi-classes via AND-consensus
produces lower BSR than combining same-class evaluators.

Usage:
    PYTHONPATH=. python scripts/experiments/exp_ensemble_bsr.py
    PYTHONPATH=. python scripts/experiments/exp_ensemble_bsr.py --out-dir evidence_pack/audit
"""

from __future__ import annotations

import argparse
from datetime import UTC, datetime
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from audit.metrics.ensemble import ensemble_bsr_experiment  # noqa: E402
from audit.shims import SHIM_REGISTRY  # noqa: E402
from scripts.audit.evaluator_audit import step1_pi_class  # noqa: E402

# v4_hard is the TCC reference used to compute BSR — it must NOT be one of
# the ensemble members, otherwise (e, v4_hard) AND-BSR collapses to e's
# false-reject rate and contaminates the same-class mean.
CORE_SHIMS = ["dxem", "ac_proxy", "mab_proxy", "c2_shim", "acov_shim"]


def _tex_escape(s: str) -> str:
    return s.replace("_", r"\_")


def main() -> None:
    parser = argparse.ArgumentParser(description="B1: Ensemble BSR experiment")
    parser.add_argument("--out-dir", type=str, default="evidence_pack/audit")
    parser.add_argument("--shims", type=str, nargs="+", default=CORE_SHIMS)
    args = parser.parse_args()

    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    # Classify pi-classes
    print("Step 1: Classifying evaluator pi-classes...")
    evaluators = {}
    pi_classes = {}
    for name in args.shims:
        ev = SHIM_REGISTRY[name]()
        evaluators[name] = ev
        s1 = step1_pi_class(ev)
        pi_classes[name] = s1["pi_class"]
        print(f"  {name}: pi_class = {s1['pi_class']}")

    # Run experiment
    print(f"\nStep 2: Computing ensemble BSR for {len(evaluators)} evaluators...")
    result = ensemble_bsr_experiment(evaluators, pi_classes)

    # Print summary
    sc = result["same_class_stats"]
    cc = result["cross_class_stats"]
    bp = result["best_and_pair"]
    print(f"\nResults ({result['n_pairs']} pairs, {result['n_episodes']} episodes):")
    print(f"  Same-class AND-BSR mean:  {sc['and_bsr_mean']:.4f} ({sc['n_pairs']} pairs)")
    print(f"  Cross-class AND-BSR mean: {cc['and_bsr_mean']:.4f} ({cc['n_pairs']} pairs)")
    print(f"  Hypothesis confirmed: {result['hypothesis_confirmed']}")
    print(
        f"  Best AND pair: {bp['evaluators'][0]} x {bp['evaluators'][1]} "
        f"(BSR={bp['and_bsr']:.4f}, cross={not bp['same_class']})"
    )

    # Per-pair detail
    print("\n  Pair details (AND-consensus BSR):")
    for p in sorted(result["pairs"], key=lambda x: x["and_bsr"]):
        tag = "SAME" if p["same_class"] else "CROSS"
        print(
            f"    {p['evaluator_a']:>10s} x {p['evaluator_b']:<10s}: "
            f"AND={p['and_bsr']:.4f}  OR={p['or_bsr']:.4f}  [{tag}]"
        )

    # Save JSON
    result["timestamp"] = datetime.now(UTC).isoformat()
    json_path = out_dir / "ensemble_bsr_results.json"
    with open(json_path, "w") as f:
        json.dump(result, f, indent=2)
    print(f"\nSaved: {json_path}")

    # Emit LaTeX macros
    macros_path = out_dir / "ensemble_bsr_macros.tex"
    macros = [
        "% Auto-generated by scripts/experiments/exp_ensemble_bsr.py",
        f"\\providecommand{{\\ensembleNPairs}}{{{result['n_pairs']}}}",
        f"\\providecommand{{\\ensembleSameAndMean}}{{{sc['and_bsr_mean']:.4f}}}",
        f"\\providecommand{{\\ensembleCrossAndMean}}{{{cc['and_bsr_mean']:.4f}}}",
        f"\\providecommand{{\\ensembleSameOrMean}}{{{sc['or_bsr_mean']:.4f}}}",
        f"\\providecommand{{\\ensembleCrossOrMean}}{{{cc['or_bsr_mean']:.4f}}}",
        f"\\providecommand{{\\ensembleSameNPairs}}{{{sc['n_pairs']}}}",
        f"\\providecommand{{\\ensembleCrossNPairs}}{{{cc['n_pairs']}}}",
        f"\\providecommand{{\\ensembleBestPairA}}{{{_tex_escape(bp['evaluators'][0])}}}",
        f"\\providecommand{{\\ensembleBestPairB}}{{{_tex_escape(bp['evaluators'][1])}}}",
        f"\\providecommand{{\\ensembleBestAndBSR}}{{{bp['and_bsr']:.4f}}}",
        f"\\providecommand{{\\ensembleHypothesis}}{{{str(result['hypothesis_confirmed']).lower()}}}",
    ]
    # Add AND-BSR reduction vs best individual
    best_indiv = min(result["individual_bsr"].values())
    reduction = best_indiv - bp["and_bsr"]
    macros.append(f"\\providecommand{{\\ensembleBestIndividualBSR}}{{{best_indiv:.4f}}}")
    macros.append(f"\\providecommand{{\\ensembleReduction}}{{{reduction:.4f}}}")

    pct_fmt = f"{sc['and_bsr_mean'] * 100:.1f}"
    macros.append(f"\\providecommand{{\\ensembleSameAndMeanPct}}{{{pct_fmt}}}")
    pct_fmt = f"{cc['and_bsr_mean'] * 100:.1f}"
    macros.append(f"\\providecommand{{\\ensembleCrossAndMeanPct}}{{{pct_fmt}}}")

    macros_path.write_text("\n".join(macros) + "\n")
    print(f"Saved: {macros_path}")


if __name__ == "__main__":
    main()
