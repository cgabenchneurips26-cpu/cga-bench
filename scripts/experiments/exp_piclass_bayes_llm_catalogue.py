#!/usr/bin/env python3
"""Y.3-extended: plug-in Bayes error under LLM-catalogue labels across 4 π.

CDE-catalogue reference (from bayes_error_macros.tex):
    ε_term = 0.436   ε_aset = 0.024   ε_nord = 0.003   ε_nctx = 0.003

We relabel every W8 episode via LLMCatalogueShim and recompute the
plug-in Bayes error per projection. Preservation of the
term > aset > nord ≈ nctx ordering is the headline Pose-B
robustness check: if ordering flips or the gaps collapse, the
paper's 4-projection taxonomy is catalogue-conditional.

The projections are implemented directly here (not imported from
scripts/audit/_projections.py) to keep the experiment self-contained
and scope-safe. They match the canonical definitions:

  π_term : terminal disposition token  (= last non-imaging action)
  π_aset : frozenset of action_ids
  π_nord : 5-min-binned ordered action sequence
  π_nctx : untimed, context-free canonical action sequence

Usage:
    PYTHONPATH=. python scripts/experiments/exp_piclass_bayes_llm_catalogue.py
"""

from __future__ import annotations

import argparse
from collections import Counter
from datetime import UTC, datetime
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from audit.shims._trajectory_cache import load_trajectory  # noqa: E402
from audit.shims._verdict_cache import get_verdict, load_w8_episodes  # noqa: E402
from audit.shims.llm_catalogue_shim import LLMCatalogueShim  # noqa: E402

OUT_DIR = ROOT / "evidence_pack" / "constraint_comparison"

# CDE-reference values from evidence_pack/theorem_v2/bayes_error_macros.tex
CDE_BAYES = {"term": 0.436, "aset": 0.024, "nord": 0.003, "nctx": 0.003}


def _actions_of(traj: dict) -> list[dict]:
    return traj.get("actions") or []


def _pi_term(traj: dict) -> str:
    """Terminal action token (last action_id)."""
    acts = _actions_of(traj)
    if not acts:
        return "__empty__"
    return str(acts[-1].get("action_id") or "__unknown__")


def _pi_aset(traj: dict) -> frozenset[str]:
    """Unordered action multiset (using frozenset for equality hashing)."""
    return frozenset(
        a.get("action_id") for a in _actions_of(traj) if a.get("action_id")
    )


def _pi_nord(traj: dict) -> tuple:
    """5-min-binned ordered action sequence (timestamps erased beyond bin)."""
    bins: list[tuple[int, str]] = []
    for a in _actions_of(traj):
        aid = a.get("action_id")
        if not aid:
            continue
        ts = float(a.get("timestamp_minutes") or 0.0)
        bins.append((int(ts // 5), aid))
    return tuple(bins)


def _pi_nctx(traj: dict) -> tuple[str, ...]:
    """Untimed, context-free ordered canonical action sequence."""
    return tuple(
        a.get("action_id") for a in _actions_of(traj) if a.get("action_id")
    )


PROJECTIONS = {
    "term": _pi_term,
    "aset": _pi_aset,
    "nord": _pi_nord,
    "nctx": _pi_nctx,
}


def _plugin_bayes_error(labels: list[bool], fibres: list) -> dict:
    """ε_π = Σ_y min(p_0(y), p_1(y)) * m_y / N."""
    n = len(labels)
    by_fibre: dict[object, list[bool]] = {}
    for lbl, y in zip(labels, fibres):
        by_fibre.setdefault(y, []).append(lbl)
    total = 0.0
    mixed_mass = 0
    n_mixed_fibres = 0
    for members in by_fibre.values():
        m = len(members)
        t = sum(members)
        p1 = t / m
        p0 = 1.0 - p1
        total += min(p0, p1) * (m / n)
        if 0 < t < m:
            mixed_mass += m
            n_mixed_fibres += 1
    return {
        "epsilon_star": round(total, 4),
        "n_fibres": len(by_fibre),
        "n_mixed_fibres": n_mixed_fibres,
        "mixed_fibre_mass_pct": round(100.0 * mixed_mass / n, 2) if n else 0.0,
    }


def _rank_agreement(cde: dict, llm: dict) -> bool:
    """Check that term > aset > nord >= nctx ordering is preserved."""
    def _order(d: dict) -> list[tuple[str, float]]:
        return sorted(d.items(), key=lambda kv: -kv[1])

    return [k for k, _ in _order(cde)] == [k for k, _ in _order(llm)]


def _emit_macros(cde: dict, llm: dict, path: Path) -> None:
    lines = [
        "% Auto-generated by exp_piclass_bayes_llm_catalogue.py",
    ]
    for proj in ("term", "aset", "nord", "nctx"):
        key = proj.capitalize()
        e = llm[proj]["epsilon_star"]
        lines.append(f"\\providecommand{{\\bayesErrLlm{key}}}{{{e:.4f}}}")
    lines.append(
        f"\\providecommand{{\\bayesErrLlmOrderingPreserved}}{{{str(_rank_agreement(CDE_BAYES, {k: v['epsilon_star'] for k, v in llm.items()})).lower()}}}"
    )
    for proj in ("term", "aset", "nord", "nctx"):
        delta = llm[proj]["epsilon_star"] - CDE_BAYES[proj]
        lines.append(
            f"\\providecommand{{\\bayesErrLlmDelta{proj.capitalize()}}}{{{delta:+.4f}}}"
        )
    path.write_text("\n".join(lines) + "\n")


def main() -> None:
    parser = argparse.ArgumentParser(description="Y.3-extended Bayes error under LLM catalogue")
    parser.add_argument("--out-dir", type=str, default=str(OUT_DIR))
    args = parser.parse_args()

    out = Path(args.out_dir)
    out.mkdir(parents=True, exist_ok=True)

    episodes = load_w8_episodes()
    eids = sorted(episodes.keys())
    print(f"Collecting trajectory + verdict vectors for {len(eids)} W8 episodes...")
    shim = LLMCatalogueShim()
    trajectories: list[dict] = []
    llm_labels: list[bool] = []
    cde_labels: list[bool] = []
    for eid in eids:
        t = load_trajectory(eid)
        if t is None:
            continue
        trajectories.append(t)
        llm_labels.append(shim.verdict({"episode_id": eid}))
        cde_labels.append(get_verdict(eid, "v4_hard"))
    print(f"  {len(trajectories)} eps have trajectories")

    # Precompute fibres per projection
    fibres_per_proj: dict[str, list] = {
        name: [fn(t) for t in trajectories] for name, fn in PROJECTIONS.items()
    }

    cde_res = {name: _plugin_bayes_error(cde_labels, fibres_per_proj[name]) for name in PROJECTIONS}
    llm_res = {name: _plugin_bayes_error(llm_labels, fibres_per_proj[name]) for name in PROJECTIONS}

    print("\nPlug-in Bayes error (labels = verdict under catalogue):")
    print(f"  {'proj':<5s}  {'CDE':>8s}  {'LLM':>8s}  {'ΔLLM-CDE':>8s}  {'n_fibres':>10s}  {'mixed_mass%':>12s}")
    for name in ("term", "aset", "nord", "nctx"):
        c = cde_res[name]
        l = llm_res[name]
        delta = l["epsilon_star"] - c["epsilon_star"]
        print(
            f"  {name:<5s}  {c['epsilon_star']:>8.4f}  {l['epsilon_star']:>8.4f}  "
            f"{delta:>+8.4f}  {l['n_fibres']:>10d}  {l['mixed_fibre_mass_pct']:>12.2f}"
        )

    cde_simple = {k: v["epsilon_star"] for k, v in cde_res.items()}
    llm_simple = {k: v["epsilon_star"] for k, v in llm_res.items()}
    preserved = _rank_agreement(cde_simple, llm_simple)
    print(f"\nOrdering preserved (term > aset > nord ≈ nctx): {preserved}")

    summary = {
        "timestamp": datetime.now(UTC).isoformat(),
        "n_episodes": len(trajectories),
        "cde_bayes": cde_res,
        "llm_bayes": llm_res,
        "ordering_preserved": preserved,
        "ordering_cde": [k for k, _ in sorted(cde_simple.items(), key=lambda kv: -kv[1])],
        "ordering_llm": [k for k, _ in sorted(llm_simple.items(), key=lambda kv: -kv[1])],
        "cde_label_pass_rate": round(sum(cde_labels) / len(cde_labels), 4) if cde_labels else 0,
        "llm_label_pass_rate": round(sum(llm_labels) / len(llm_labels), 4) if llm_labels else 0,
    }
    (out / "y3_bayes_extended_results.json").write_text(json.dumps(summary, indent=2) + "\n")
    _emit_macros(CDE_BAYES, llm_res, out / "y3_bayes_extended_macros.tex")
    print(f"\nSaved: {out}/y3_bayes_extended_{{results.json, macros.tex}}")


if __name__ == "__main__":
    main()
