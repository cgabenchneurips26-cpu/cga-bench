#!/usr/bin/env python3
"""T1-6: Random-clustering null baseline (canonical-6 scope).

Distinct from T0-1 permutation: T0-1 shuffles pi-class labels freely
(label cardinality preserved because it's a permutation of a list).
T1-6 draws B random partitions of the 6 evaluators into groups with
sizes exactly matching the observed pi-class cardinality (term=2,
nctx=3, aset=1). For each partition we compute within-cluster −
cross-cluster mean τ̄ gap, then report where the observed gap sits in
the sorted null distribution.

This tests whether *any* 4-class partition with the right group sizes
would show the same gap — i.e. whether pi-class is special relative
to arbitrary same-size groupings.

Usage:
    PYTHONPATH=. python scripts/experiments/exp_piclass_random_clustering.py
"""

from __future__ import annotations

import argparse
from datetime import UTC, datetime
import json
from pathlib import Path
import random
import statistics
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

OUT_DIR = ROOT / "evidence_pack" / "audit"
C6_PATH = ROOT / "evidence_pack" / "audit" / "c6_audit_guided_selection.json"
NONDEGEN_EPS = 1e-3


def _same_cross_nondegen_gap(
    pairs: list[dict], partition: dict[str, str]
) -> float:
    same = []
    cross = []
    for p in pairs:
        t = float(p["tau"])
        if abs(t) <= NONDEGEN_EPS:
            continue
        if partition[p["evaluator_a"]] == partition[p["evaluator_b"]]:
            same.append(t)
        else:
            cross.append(t)
    s = statistics.fmean(same) if same else 0.0
    c = statistics.fmean(cross) if cross else 0.0
    return s - c


def _size_preserving_partition(
    names: list[str], class_sizes: dict[str, int], rng: random.Random
) -> dict[str, str]:
    """Return a partition that matches the observed pi-class size distribution."""
    shuffled = names[:]
    rng.shuffle(shuffled)
    out: dict[str, str] = {}
    cursor = 0
    for cls, size in class_sizes.items():
        for _ in range(size):
            out[shuffled[cursor]] = cls
            cursor += 1
    return out


def run_random_clustering(
    pairs: list[dict],
    pi_classes: dict[str, str],
    B: int,
    seed: int,
) -> dict:
    names = list(pi_classes.keys())
    class_sizes: dict[str, int] = {}
    for c in pi_classes.values():
        class_sizes[c] = class_sizes.get(c, 0) + 1

    rng = random.Random(seed)
    obs_gap = _same_cross_nondegen_gap(pairs, pi_classes)
    null_gaps: list[float] = []
    for _ in range(B):
        part = _size_preserving_partition(names, class_sizes, rng)
        null_gaps.append(_same_cross_nondegen_gap(pairs, part))

    # Upper-tail test: fraction of null partitions whose gap is >= observed
    n_ge = sum(1 for g in null_gaps if g >= obs_gap)
    percentile_rank = 1 - (n_ge / B)  # higher = more extreme
    return {
        "B": B,
        "seed": seed,
        "class_sizes": class_sizes,
        "n_evaluators": len(names),
        "n_pairs": len(pairs),
        "obs_gap": round(obs_gap, 4),
        "null_mean": round(statistics.fmean(null_gaps), 4),
        "null_sd": round(statistics.pstdev(null_gaps), 4) if B > 1 else 0.0,
        "n_ge_observed": n_ge,
        "percentile_rank": round(percentile_rank, 4),
        "upper_tail_p": round(n_ge / B, 4),
    }


def _emit_macros(res: dict, path: Path) -> None:
    p = res["upper_tail_p"]
    p_fmt = f"< {1 / res['B']:.0e}" if p == 0.0 else f"{p:.4f}"
    lines = [
        "% Auto-generated by scripts/experiments/exp_piclass_random_clustering.py",
        f"\\providecommand{{\\piRandClusterB}}{{{res['B']:,}}}",
        f"\\providecommand{{\\piRandClusterObsGap}}{{{res['obs_gap']:.4f}}}",
        f"\\providecommand{{\\piRandClusterNullMean}}{{{res['null_mean']:.4f}}}",
        f"\\providecommand{{\\piRandClusterNullSd}}{{{res['null_sd']:.4f}}}",
        f"\\providecommand{{\\piRandClusterNGe}}{{{res['n_ge_observed']}}}",
        f"\\providecommand{{\\piRandClusterPct}}{{{res['percentile_rank']:.4f}}}",
        f"\\providecommand{{\\piRandClusterP}}{{{p_fmt}}}",
    ]
    path.write_text("\n".join(lines) + "\n")


def main() -> None:
    parser = argparse.ArgumentParser(description="T1-6 random-clustering null baseline (canonical-6)")
    parser.add_argument("--B", type=int, default=10_000)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--out-dir", type=str, default=str(OUT_DIR))
    args = parser.parse_args()

    with open(C6_PATH) as f:
        data = json.load(f)
    pi_classes = data["pi_classes"]
    pairs = data["pairs"]
    print(f"Loaded {len(pi_classes)} evaluators, {len(pairs)} pair τ values")
    print(f"Pi-class sizes: {dict((c, list(pi_classes.values()).count(c)) for c in set(pi_classes.values()))}")

    res = run_random_clustering(pairs, pi_classes, args.B, args.seed)
    res["timestamp"] = datetime.now(UTC).isoformat()
    print(
        f"\n[T1-6] obs_gap={res['obs_gap']:.4f}  "
        f"null_mean={res['null_mean']:.4f}  null_sd={res['null_sd']:.4f}  "
        f"n_ge={res['n_ge_observed']}/{res['B']}  "
        f"upper-tail p={res['upper_tail_p']:.4f}"
    )

    out = Path(args.out_dir)
    out.mkdir(parents=True, exist_ok=True)
    (out / "piclass_random_cluster_canonical6_results.json").write_text(
        json.dumps(res, indent=2) + "\n"
    )
    _emit_macros(res, out / "piclass_random_cluster_canonical6_macros.tex")
    print("Saved: piclass_random_cluster_canonical6_{results.json, macros.tex}")


if __name__ == "__main__":
    main()
