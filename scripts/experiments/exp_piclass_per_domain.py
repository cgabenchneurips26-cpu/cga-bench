#!/usr/bin/env python3
"""T1-5: Per-domain within/cross τ̄ box-plot (canonical-6 scope).

Tests whether the π-class within-vs-cross gap is uniform across the
25 CPG domains, or driven by a subset. For each domain prefix we
recompute the canonical-6 pair-wise τ on the episodes of that domain
and report the same/cross mean tuples.

A domain-level "reversal" (gap < 0) is the negative signal we look
for; its count is the headline ``\\piPerDomainNReversals`` macro.

Usage:
    PYTHONPATH=. python scripts/experiments/exp_piclass_per_domain.py
    PYTHONPATH=. python scripts/experiments/exp_piclass_per_domain.py --skip-figure
"""

from __future__ import annotations

import argparse
from datetime import UTC, datetime
import itertools
import json
from pathlib import Path
import statistics
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from audit.metrics.selection import binary_tau  # noqa: E402
from audit.shims._verdict_cache import load_w8_episodes  # noqa: E402
from scripts.experiments.exp_piclass_heldout import (  # noqa: E402
    CANONICAL_SIX,
    _pair_results,
    _same_cross_nondegen,
    _verdict_col,
)

OUT_DIR = ROOT / "evidence_pack" / "audit"
C6_PATH = ROOT / "evidence_pack" / "audit" / "c6_audit_guided_selection.json"

# 25 CPG domain prefixes (20 core + 5 held-out)
DOMAIN_PREFIXES: tuple[str, ...] = (
    "aabb_t",
    "aha_stemi",
    "aha_stroke",
    "aha_hf",
    "acls",
    "ada_dka",
    "anaphyl",
    "asthma",
    "atrial_fib",
    "cap_pneu",
    "copd",
    "gi_bleed",
    "hyper_emerg",
    "kdigo",
    "meningitis",
    "pe_",
    "sepsis",
    "status_epi",
    "stemi_",
    "universal",
    # held-out 5
    "aba_burn",
    "acog_o",
    "apa_a",
    "pals_p",
    "toxicology_m",
)


def _compute_domain_tau(
    episodes: dict[str, dict],
    pi_classes: dict[str, str],
    prefix: str,
) -> dict | None:
    subset = {
        eid: ep for eid, ep in episodes.items() if ep["scenario_id"].startswith(prefix)
    }
    if not subset:
        return None
    ep_ids = sorted(subset.keys())
    verdicts = {
        n: [_verdict_col(subset[e], n) for e in ep_ids] for n in CANONICAL_SIX
    }
    pairs = _pair_results(verdicts, pi_classes)
    s, c, ns, nc = _same_cross_nondegen(pairs, pi_classes)
    return {
        "prefix": prefix,
        "n_episodes": len(ep_ids),
        "same_mean": round(s, 4),
        "cross_mean": round(c, 4),
        "gap": round(s - c, 4),
        "n_same_nondegen": ns,
        "n_cross_nondegen": nc,
    }


def _emit_macros(summary: dict, path: Path) -> None:
    rows = summary["domains"]
    nreversal = sum(1 for r in rows if r["gap"] < 0)
    gaps = [r["gap"] for r in rows]
    median_gap = statistics.median(gaps) if gaps else 0.0
    lines = [
        "% Auto-generated by scripts/experiments/exp_piclass_per_domain.py",
        f"\\providecommand{{\\piPerDomainN}}{{{len(rows)}}}",
        f"\\providecommand{{\\piPerDomainMedianGap}}{{{median_gap:.4f}}}",
        f"\\providecommand{{\\piPerDomainNReversals}}{{{nreversal}}}",
        f"\\providecommand{{\\piPerDomainMinGap}}{{{min(gaps):.4f}}}",
        f"\\providecommand{{\\piPerDomainMaxGap}}{{{max(gaps):.4f}}}",
    ]
    path.write_text("\n".join(lines) + "\n")


def _maybe_plot(rows: list[dict], path: Path) -> bool:
    try:
        import matplotlib  # noqa: F401
        import matplotlib.pyplot as plt
    except ImportError:
        return False
    fig, ax = plt.subplots(figsize=(12, 5))
    names = [r["prefix"] for r in rows]
    same_vals = [r["same_mean"] for r in rows]
    cross_vals = [r["cross_mean"] for r in rows]
    x = range(len(rows))
    width = 0.38
    ax.bar([i - width / 2 for i in x], same_vals, width, label="within-class τ̄", alpha=0.8)
    ax.bar([i + width / 2 for i in x], cross_vals, width, label="cross-class τ̄", alpha=0.8)
    ax.set_xticks(list(x))
    ax.set_xticklabels(names, rotation=60, ha="right", fontsize=8)
    ax.axhline(0.0, color="black", linewidth=0.5)
    ax.set_ylabel("Mean pair τ (canonical-6)")
    ax.set_title("Per-domain within vs cross-class agreement")
    ax.legend()
    fig.tight_layout()
    fig.savefig(path, dpi=120)
    plt.close(fig)
    return True


def main() -> None:
    parser = argparse.ArgumentParser(description="T1-5 per-domain within/cross τ̄ (canonical-6)")
    parser.add_argument("--skip-figure", action="store_true")
    parser.add_argument("--out-dir", type=str, default=str(OUT_DIR))
    args = parser.parse_args()

    with open(C6_PATH) as f:
        pi_classes = json.load(f)["pi_classes"]
    eps = load_w8_episodes()
    print(f"Working on {len(eps)} W8 episodes across {len(DOMAIN_PREFIXES)} domain prefixes.")

    rows: list[dict] = []
    for prefix in DOMAIN_PREFIXES:
        r = _compute_domain_tau(eps, pi_classes, prefix)
        if r is None:
            print(f"  skip {prefix!r} (0 episodes)")
            continue
        rows.append(r)
        print(
            f"  {prefix:>15s}: n={r['n_episodes']:>5d}  "
            f"same={r['same_mean']:>7.4f}  cross={r['cross_mean']:>7.4f}  "
            f"gap={r['gap']:>+7.4f}"
        )

    nreversal = sum(1 for r in rows if r["gap"] < 0)
    gaps = [r["gap"] for r in rows]
    print(
        f"\n[T1-5 summary] domains={len(rows)}  "
        f"median gap={statistics.median(gaps):.4f}  "
        f"reversals={nreversal}/{len(rows)}  "
        f"gap range=[{min(gaps):.4f}, {max(gaps):.4f}]"
    )

    summary = {
        "timestamp": datetime.now(UTC).isoformat(),
        "canonical_six": list(CANONICAL_SIX),
        "pi_classes": pi_classes,
        "domains": rows,
        "median_gap": round(statistics.median(gaps), 4) if gaps else 0.0,
        "n_reversals": nreversal,
    }
    out = Path(args.out_dir)
    out.mkdir(parents=True, exist_ok=True)
    (out / "piclass_per_domain_canonical6_results.json").write_text(
        json.dumps(summary, indent=2) + "\n"
    )
    _emit_macros(summary, out / "piclass_per_domain_canonical6_macros.tex")

    if not args.skip_figure:
        fig_path = ROOT / "paper" / "figures" / "piclass_per_domain_canonical6.pdf"
        fig_path.parent.mkdir(parents=True, exist_ok=True)
        ok = _maybe_plot(rows, fig_path)
        if ok:
            print(f"Saved figure: {fig_path}")
        else:
            print("matplotlib unavailable; skipping figure")

    print(f"Saved: piclass_per_domain_canonical6_{{results.json, macros.tex}}")


if __name__ == "__main__":
    main()
