#!/usr/bin/env python3
"""Y.3 matcher-threshold sensitivity sweep.

The 50% MUST-coverage threshold baked into LLMCatalogueShim is one
knob; the paper's catalogue-conditional claim (τ=-0.075) may be an
artefact of that knob. This sweep reruns the invariance pair τ at
thresholds {0.00, 0.25, 0.50, 0.75, 1.00}, reporting how τ moves.

We also vary the matcher's token-intersection policy by enabling /
disabling stopword filtering (the default strips generic clinical
prose tokens like "patient", "administer", "minutes").

Output
------
  evidence_pack/constraint_comparison/y3_threshold_sweep_results.json
  evidence_pack/constraint_comparison/y3_threshold_sweep_macros.tex

Usage
-----
    PYTHONPATH=. python scripts/experiments/exp_piclass_y3_threshold_sweep.py
"""

from __future__ import annotations

import argparse
from datetime import UTC, datetime
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from audit.metrics.selection import binary_tau  # noqa: E402
from audit.shims import llm_catalogue_shim as lcs  # noqa: E402
from audit.shims._trajectory_cache import load_trajectory  # noqa: E402
from audit.shims._verdict_cache import get_verdict, load_w8_episodes  # noqa: E402

OUT_DIR = ROOT / "evidence_pack" / "constraint_comparison"

THRESHOLDS = (0.0, 0.25, 0.5, 0.75, 1.0)


def _verdict_at_threshold(
    traj: dict, cat: dict[str, list[str]], thr: float
) -> bool:
    if traj is None or cat is None:
        return False
    if not cat["MUST"] and not cat["FORBIDDEN"]:
        return True
    performed = {
        a.get("action_id")
        for a in (traj.get("actions") or [])
        if a.get("action_id")
    }
    # FORBIDDEN short-circuits
    for f in cat["FORBIDDEN"]:
        if lcs._fuzzy_hit(f, performed):
            return False
    if not cat["MUST"]:
        return True
    hits = sum(1 for m in cat["MUST"] if lcs._fuzzy_hit(m, performed))
    return hits / len(cat["MUST"]) >= thr


def main() -> None:
    parser = argparse.ArgumentParser(description="Y.3 threshold sensitivity sweep")
    parser.add_argument("--out-dir", type=str, default=str(OUT_DIR))
    args = parser.parse_args()

    eps = load_w8_episodes()
    eids = sorted(eps.keys())
    # Pre-load trajectories + catalogues
    print(f"Loading trajectories for {len(eids)} W8 episodes...")
    traj_by_eid: dict[str, dict] = {}
    for eid in eids:
        t = load_trajectory(eid)
        if t is not None:
            traj_by_eid[eid] = t
    # Resolve catalogue per scenario_id once
    cat_by_scenario: dict[str, dict] = {}
    for eid, t in traj_by_eid.items():
        sid = t.get("scenario_id", "")
        if sid in cat_by_scenario:
            continue
        cpg = lcs._resolve_cpg_name(sid)
        cat_by_scenario[sid] = lcs._load_catalogue(cpg) if cpg else {"MUST": [], "FORBIDDEN": []}

    ref = [get_verdict(eid, "v4_hard") for eid in eids]
    rows: list[dict] = []
    for thr in THRESHOLDS:
        vs: list[bool] = []
        for eid in eids:
            t = traj_by_eid.get(eid)
            if t is None:
                vs.append(False)
                continue
            cat = cat_by_scenario.get(t.get("scenario_id", ""), {"MUST": [], "FORBIDDEN": []})
            vs.append(_verdict_at_threshold(t, cat, thr))
        tau = binary_tau(vs, ref)
        agree = sum(1 for v, r in zip(vs, ref) if v == r) / len(eids)
        rows.append(
            {
                "threshold": thr,
                "llm_pass_rate": round(sum(vs) / len(vs), 4),
                "v4_pass_rate": round(sum(ref) / len(ref), 4),
                "agreement_rate": round(agree, 4),
                "pair_tau_vs_v4_hard": round(tau, 4),
            }
        )
        print(
            f"  thr={thr:.2f}  llm_pass={rows[-1]['llm_pass_rate']:.4f}  "
            f"agree={agree*100:.2f}%  τ={tau:+.4f}"
        )

    summary = {
        "timestamp": datetime.now(UTC).isoformat(),
        "n_episodes": len(eids),
        "thresholds": list(THRESHOLDS),
        "rows": rows,
        "min_abs_tau": round(min(abs(r["pair_tau_vs_v4_hard"]) for r in rows), 4),
        "max_abs_tau": round(max(abs(r["pair_tau_vs_v4_hard"]) for r in rows), 4),
        "tau_sign_changes_across_thresholds": sum(
            1
            for i in range(1, len(rows))
            if (rows[i - 1]["pair_tau_vs_v4_hard"] > 0)
            != (rows[i]["pair_tau_vs_v4_hard"] > 0)
        ),
    }
    out = Path(args.out_dir)
    out.mkdir(parents=True, exist_ok=True)
    (out / "y3_threshold_sweep_results.json").write_text(json.dumps(summary, indent=2) + "\n")
    # macros
    lines = ["% Auto-generated by exp_piclass_y3_threshold_sweep.py"]
    for r in rows:
        key = str(int(round(r["threshold"] * 100))).zfill(3)
        lines.append(f"\\providecommand{{\\piYThreshTau{key}}}{{{r['pair_tau_vs_v4_hard']:+.4f}}}")
        lines.append(f"\\providecommand{{\\piYThreshPass{key}}}{{{r['llm_pass_rate']:.4f}}}")
    lines.append(
        f"\\providecommand{{\\piYThreshMinAbsTau}}{{{summary['min_abs_tau']:.4f}}}"
    )
    lines.append(
        f"\\providecommand{{\\piYThreshMaxAbsTau}}{{{summary['max_abs_tau']:.4f}}}"
    )
    (out / "y3_threshold_sweep_macros.tex").write_text("\n".join(lines) + "\n")
    print(f"\nSaved: {out}/y3_threshold_sweep_{{results.json, macros.tex}}")


if __name__ == "__main__":
    main()
