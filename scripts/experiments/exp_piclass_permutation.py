#!/usr/bin/env python3
"""T0-1: Permutation test on the within-cross τ̄ gap.

Null hypothesis: the observed gap between within-class and cross-class
mean pair-wise Kendall τ is achievable under random re-labellings of
pi-class. We reject this by shuffling the pi-class column across the
evaluators (preserving the cardinality of each class) B=10,000 times
and comparing to the observed gap of 0.4729 - 0.1915 = 0.2814.

Usage:
    PYTHONPATH=. python scripts/experiments/exp_piclass_permutation.py
    PYTHONPATH=. python scripts/experiments/exp_piclass_permutation.py --B 10000 --seed 42
"""

from __future__ import annotations

import argparse
from datetime import UTC, datetime
import json
from pathlib import Path
import random
import statistics
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

SELECTION_PATH = ROOT / "evidence_pack" / "audit" / "c6_audit_guided_selection.json"
OUT_DIR = ROOT / "evidence_pack" / "audit"

NONDEGEN_EPS = 1e-12  # treat |τ| < eps as degenerate


def load_pairs() -> tuple[dict[str, str], list[dict]]:
    """Return (pi_class_map, list_of_pair_records)."""
    with open(SELECTION_PATH) as f:
        data = json.load(f)
    return data["pi_classes"], data["pairs"]


def _mean_nondegen(vals: list[float]) -> float | None:
    kept = [v for v in vals if abs(v) > NONDEGEN_EPS]
    if not kept:
        return None
    return sum(kept) / len(kept)


def _compute_gap(pi_class: dict[str, str], pairs: list[dict]) -> float:
    """Recompute within/cross mean τ on non-degenerate pairs; return gap."""
    same: list[float] = []
    cross: list[float] = []
    for p in pairs:
        tau = float(p["tau"])
        if pi_class[p["evaluator_a"]] == pi_class[p["evaluator_b"]]:
            same.append(tau)
        else:
            cross.append(tau)
    s = _mean_nondegen(same) or 0.0
    c = _mean_nondegen(cross) or 0.0
    return s - c


def permutation_test(
    pi_class: dict[str, str],
    pairs: list[dict],
    B: int,
    seed: int,
) -> dict:
    names = list(pi_class.keys())
    labels = list(pi_class.values())
    rng = random.Random(seed)

    obs_gap = _compute_gap(pi_class, pairs)

    null_gaps: list[float] = []
    for _ in range(B):
        shuffled = labels[:]
        rng.shuffle(shuffled)
        perm_map = dict(zip(names, shuffled))
        null_gaps.append(_compute_gap(perm_map, pairs))

    n_extreme = sum(1 for g in null_gaps if abs(g) >= abs(obs_gap))
    p_value = n_extreme / B
    return {
        "B": B,
        "seed": seed,
        "n_evaluators": len(names),
        "n_pairs": len(pairs),
        "obs_gap": round(obs_gap, 6),
        "null_mean": round(statistics.fmean(null_gaps), 6),
        "null_sd": round(statistics.pstdev(null_gaps), 6) if B > 1 else 0.0,
        "n_extreme": n_extreme,
        "p_value": p_value,
    }


def _fmt_p(p: float, B: int) -> str:
    if p == 0.0:
        return f"< {1 / B:.0e}"
    return f"{p:.4f}"


def _emit_macros(res: dict, path: Path) -> None:
    p_fmt = _fmt_p(res["p_value"], res["B"])
    lines = [
        "% Auto-generated by scripts/experiments/exp_piclass_permutation.py",
        f"\\providecommand{{\\piPermB}}{{{res['B']:,}}}",
        f"\\providecommand{{\\piPermSeed}}{{{res['seed']}}}",
        f"\\providecommand{{\\piPermObsGap}}{{{res['obs_gap']:.4f}}}",
        f"\\providecommand{{\\piPermNullMean}}{{{res['null_mean']:.4f}}}",
        f"\\providecommand{{\\piPermNullSd}}{{{res['null_sd']:.4f}}}",
        f"\\providecommand{{\\piPermNExtreme}}{{{res['n_extreme']}}}",
        f"\\providecommand{{\\piPermP}}{{{p_fmt}}}",
    ]
    path.write_text("\n".join(lines) + "\n")


def main() -> None:
    parser = argparse.ArgumentParser(description="T0-1 pi-class permutation test")
    parser.add_argument("--B", type=int, default=10_000)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--out-dir", type=str, default=str(OUT_DIR))
    args = parser.parse_args()

    pi_class, pairs = load_pairs()
    print(f"Loaded {len(pi_class)} evaluators, {len(pairs)} pairs")
    print(f"pi_class: {pi_class}")

    res = permutation_test(pi_class, pairs, args.B, args.seed)
    res["timestamp"] = datetime.now(UTC).isoformat()

    print(
        f"\nobs_gap = {res['obs_gap']:.4f}, "
        f"null_mean = {res['null_mean']:.4f} (sd = {res['null_sd']:.4f})"
    )
    print(f"n_extreme = {res['n_extreme']}/{res['B']}")
    print(f"p_value = {_fmt_p(res['p_value'], res['B'])}")

    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    json_path = out_dir / "piclass_permutation_results.json"
    json_path.write_text(json.dumps(res, indent=2) + "\n")
    print(f"\nSaved: {json_path}")

    tex_path = out_dir / "piclass_permutation_macros.tex"
    _emit_macros(res, tex_path)
    print(f"Saved: {tex_path}")


if __name__ == "__main__":
    main()
