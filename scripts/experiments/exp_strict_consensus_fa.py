#!/usr/bin/env python3
"""
EX-34: Strict Non-Degenerate FA Intersection
=============================================
Computes strict false-accept rates excluding degenerate evaluators (TOM/DxEM = 100% pass).

Defends against attack A1: "hero FA includes TOM which always passes"

Input:  evidence_pack/analysis/verdict_matrix_v6.json
Output: evidence_pack/ex34_strict_fa/strict_fa.json
        evidence_pack/ex34_strict_fa/macros.tex
"""

import json
import os
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
VERDICT_PATH = ROOT / "evidence_pack" / "analysis" / "verdict_matrix_v6.json"
OUTPUT_DIR = ROOT / "evidence_pack" / "ex34_strict_fa"


def load_verdict_matrix() -> list[dict]:
    """Load per-episode verdict data."""
    with open(VERDICT_PATH) as f:
        data = json.load(f)
    return data["per_episode"]


def compute_strict_fa(episodes: list[dict]) -> dict:
    """Compute strict FA intersections."""
    n_total = len(episodes)

    # Current "all three" = TOM ∩ ASC ∩ CwT (degenerate because TOM=100%)
    fa_current = [
        ep for ep in episodes
        if ep["dxem"] and ep["ac_proxy"] and ep["c2_pass"] and ep["v4_hard"]
    ]

    # Strict FA3 = ASC ∩ PAF ∩ CwT (excludes degenerate TOM)
    fa_strict3 = [
        ep for ep in episodes
        if ep["ac_proxy"] and ep["mab_proxy"] and ep["c2_pass"] and ep["v4_hard"]
    ]

    # Strict FA4 = TOM ∩ ASC ∩ PAF ∩ CwT (all four, including TOM)
    fa_strict4 = [
        ep for ep in episodes
        if ep["dxem"] and ep["ac_proxy"] and ep["mab_proxy"] and ep["c2_pass"]
        and ep["v4_hard"]
    ]

    # Per-model breakdown for strictFA3
    model_breakdown = defaultdict(lambda: {"total": 0, "fa3": 0})
    for ep in episodes:
        model = ep["model_dir"]
        model_breakdown[model]["total"] += 1
    for ep in fa_strict3:
        model_breakdown[ep["model_dir"]]["fa3"] += 1

    per_model = {}
    for model, counts in sorted(model_breakdown.items()):
        rate = counts["fa3"] / counts["total"] * 100 if counts["total"] > 0 else 0
        per_model[model] = {
            "total": counts["total"],
            "fa3_count": counts["fa3"],
            "fa3_rate": round(rate, 1),
        }

    # Critical severity among strictFA3
    fa3_critical = [ep for ep in fa_strict3 if ep.get("v4_crit", False)]
    critical_pct = len(fa3_critical) / max(len(fa_strict3), 1) * 100

    # Domain breakdown (top-5 by FA3 count)
    domain_counts: Counter[str] = Counter()
    for ep in fa_strict3:
        # Extract domain from scenario_id (first part before underscore pattern)
        sid = ep.get("scenario_id", "")
        parts = sid.split("_")
        # Use the graph/domain prefix
        if len(parts) >= 2:
            domain_counts[parts[0] + "_" + parts[1]] += 1
        else:
            domain_counts[sid] += 1

    top_domains = domain_counts.most_common(10)

    # Violation type distribution among strictFA3
    viol_type_counts: Counter[str] = Counter()
    for ep in fa_strict3:
        for vt in ep.get("viol_types", []):
            viol_type_counts[vt] += 1

    # Median violations per FA3 episode
    fa3_viols = sorted([ep["n_viols"] for ep in fa_strict3])
    median_viols = fa3_viols[len(fa3_viols) // 2] if fa3_viols else 0

    return {
        "n_total": n_total,
        "current_fa": {
            "label": "TOM ∩ ASC ∩ CwT (current, degenerate)",
            "count": len(fa_current),
            "rate": round(len(fa_current) / n_total * 100, 1),
        },
        "strict_fa3": {
            "label": "ASC ∩ PAF ∩ CwT (non-degenerate)",
            "count": len(fa_strict3),
            "rate": round(len(fa_strict3) / n_total * 100, 1),
            "critical_count": len(fa3_critical),
            "critical_pct": round(critical_pct, 1),
            "median_violations": median_viols,
            "per_model": per_model,
            "top_domains": top_domains,
            "violation_types": dict(viol_type_counts.most_common()),
        },
        "strict_fa4": {
            "label": "TOM ∩ ASC ∩ PAF ∩ CwT (all four)",
            "count": len(fa_strict4),
            "rate": round(len(fa_strict4) / n_total * 100, 1),
        },
    }


def generate_macros(results: dict) -> str:
    """Generate LaTeX macros."""
    fa3 = results["strict_fa3"]
    fa4 = results["strict_fa4"]
    current = results["current_fa"]

    lines = [
        "% EX-34: Strict Non-Degenerate FA Intersection",
        "% Auto-generated by exp_strict_consensus_fa.py",
        "",
        f"\\newcommand{{\\strictFAThree}}{{{fa3['rate']}}}",
        f"\\newcommand{{\\strictFAThreeCount}}{{{fa3['count']}}}",
        f"\\newcommand{{\\strictFAFour}}{{{fa4['rate']}}}",
        f"\\newcommand{{\\strictFAFourCount}}{{{fa4['count']}}}",
        f"\\newcommand{{\\strictFACriticalPct}}{{{fa3['critical_pct']}}}",
        f"\\newcommand{{\\strictFACriticalCount}}{{{fa3['critical_count']}}}",
        f"\\newcommand{{\\strictFAMedianViols}}{{{fa3['median_violations']}}}",
    ]
    return "\n".join(lines)


def main() -> None:
    print("Loading verdict matrix...")
    episodes = load_verdict_matrix()
    print(f"  {len(episodes)} episodes loaded")

    print("\nComputing strict FA intersections...")
    results = compute_strict_fa(episodes)

    print(f"\n  Current FA (TOM∩ASC∩CwT): {results['current_fa']['rate']}% "
          f"({results['current_fa']['count']})")
    print(f"  Strict FA3 (ASC∩PAF∩CwT): {results['strict_fa3']['rate']}% "
          f"({results['strict_fa3']['count']})")
    print(f"  Strict FA4 (all four):     {results['strict_fa4']['rate']}% "
          f"({results['strict_fa4']['count']})")
    print(f"  Critical severity:         {results['strict_fa3']['critical_pct']}% "
          f"({results['strict_fa3']['critical_count']})")
    print(f"  Median violations/FA3 ep:  {results['strict_fa3']['median_violations']}")

    print("\n  Per-model strictFA3:")
    for model, data in results["strict_fa3"]["per_model"].items():
        print(f"    {model}: {data['fa3_rate']}% ({data['fa3_count']}/{data['total']})")

    os.makedirs(OUTPUT_DIR, exist_ok=True)

    with open(OUTPUT_DIR / "strict_fa.json", "w") as f:
        json.dump(results, f, indent=2)

    macros = generate_macros(results)
    with open(OUTPUT_DIR / "macros.tex", "w") as f:
        f.write(macros)

    print(f"\nSaved to {OUTPUT_DIR}/")


if __name__ == "__main__":
    main()
