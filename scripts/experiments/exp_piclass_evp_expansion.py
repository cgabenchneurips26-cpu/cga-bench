#!/usr/bin/env python3
"""T2-11 (reframed): EVP expansion as dilution evidence.

Original plan cast T2-11 as "six third-party evaluators that harness
auto-classifies into their predicted pi-class". Given the pool
dilution finding (docs/260423_piclass_pool_dilution_finding.md), we
reframe: the 6 external-benchmark bridges (2 style emulators + 4
native scorers) are exactly the evaluators whose hypothesised pi-class
disagrees with the harness-assigned class, and that disagreement is
*why* the extended-pool τ̄ gap dilutes.

This script tabulates, for each of the 6 ext_* bridges:
  - hypothesised pi-class (from the subclass `pi_family_hypothesis`
    attribute)
  - harness-assigned pi-class (from step1_pi_class behavioural test)
  - mismatch flag
  - BSR for context

The table becomes the honest Appendix E content: "the harness makes
its own classification call and disagrees with the authors' prior
hypothesis on 6/6 external bridges — that disagreement is the
headline signal for why the taxonomy is family-specific."
"""

from __future__ import annotations

import argparse
from datetime import UTC, datetime
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

OUT_DIR = ROOT / "evidence_pack" / "audit"

EXT_BRIDGES: tuple[str, ...] = (
    "ext_medagent_style",
    "ext_healthbench_style",
    "ext_medagent_native",
    "ext_art_native",
    "ext_agentehr_native",
    "ext_healthbench_native",
)


def _bsr_from_verdicts(verd: list[bool], ref: list[bool]) -> float:
    n = len(verd)
    if n == 0:
        return 0.0
    return sum(1 for v, r in zip(verd, ref) if v != r) / n


def main() -> None:
    parser = argparse.ArgumentParser(description="T2-11 reframed EVP expansion table")
    parser.add_argument("--out-dir", type=str, default=str(OUT_DIR))
    args = parser.parse_args()

    from audit.shims import SHIM_REGISTRY
    from audit.shims._verdict_cache import get_verdict, load_w8_episodes
    from scripts.audit.evaluator_audit import step1_pi_class

    eps = load_w8_episodes()
    ep_ids = sorted(eps.keys())
    ref = [get_verdict(eid, "v4_hard") for eid in ep_ids]
    rows: list[dict] = []
    for key in EXT_BRIDGES:
        if key not in SHIM_REGISTRY:
            print(f"  skip {key}: not in SHIM_REGISTRY")
            continue
        cls = SHIM_REGISTRY[key]
        ev = cls()
        hypothesis = getattr(ev, "pi_family_hypothesis", "unknown")
        s1 = step1_pi_class(ev)
        actual = s1["pi_class"]
        print(f"  classify + verdict: {key} ... hypothesis={hypothesis}, actual={actual}")
        verd = [ev.verdict({"episode_id": eid}) for eid in ep_ids]
        bsr = _bsr_from_verdicts(verd, ref)
        rows.append(
            {
                "shim_key": key,
                "benchmark_name": getattr(ev, "benchmark_name", ev.meta.name),
                "bridge_kind": "native" if "_native" in key else "style",
                "hypothesis": hypothesis,
                "actual": actual,
                "match": hypothesis == actual,
                "bsr": round(bsr, 4),
            }
        )

    n_match = sum(1 for r in rows if r["match"])
    print(f"\n[T2-11] Hypothesis vs actual pi-class: {n_match}/{len(rows)} match")
    for r in rows:
        flag = "MATCH" if r["match"] else "MISS "
        print(
            f"  {flag}  {r['shim_key']:<24s}  "
            f"hyp={r['hypothesis']:<6s}  actual={r['actual']:<6s}  BSR={r['bsr']:.4f}"
        )

    summary = {
        "timestamp": datetime.now(UTC).isoformat(),
        "bridges": rows,
        "n_match": n_match,
        "n_total": len(rows),
    }
    out = Path(args.out_dir)
    out.mkdir(parents=True, exist_ok=True)
    (out / "piclass_evp_expansion_results.json").write_text(json.dumps(summary, indent=2) + "\n")
    lines = [
        "% Auto-generated by scripts/experiments/exp_piclass_evp_expansion.py",
        f"\\providecommand{{\\piEvpNTotal}}{{{len(rows)}}}",
        f"\\providecommand{{\\piEvpNMatch}}{{{n_match}}}",
        f"\\providecommand{{\\piEvpNMiss}}{{{len(rows) - n_match}}}",
    ]
    (out / "piclass_evp_expansion_macros.tex").write_text("\n".join(lines) + "\n")
    print("Saved: piclass_evp_expansion_{results.json, macros.tex}")


if __name__ == "__main__":
    main()
