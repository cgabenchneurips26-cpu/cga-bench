"""LLM-as-judge evaluator — cached offline verdicts.

Pre-computed verdicts are loaded from evidence_pack/audit/llm_judge_cache.json
(generated by scripts/audit/precompute_llm_judge.py). The evaluator does NOT
call any LLM at audit time — it is a pure cache lookup, satisfying the
Evaluator ABC determinism contract.

Purpose: EVP-2 extensibility proof — demonstrates the audit harness
accepts LLM-as-judge evaluators, the reviewer's most likely question.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from audit.evaluator_base import Evaluator, EvaluatorMeta

_CACHE_PATH = Path(__file__).resolve().parent.parent.parent / "evidence_pack" / "audit" / "llm_judge_cache.json"


class LLMJudgeEvaluator(Evaluator):
    """Cached LLM-as-judge verdicts (pre-computed offline)."""

    meta = EvaluatorMeta(
        name="LLMJudge",
        family="LLM-judge",
        source="llm_judge_cache.json",
    )

    def __init__(self) -> None:
        if _CACHE_PATH.exists():
            with open(_CACHE_PATH) as f:
                self._cache: dict[str, bool] = json.load(f)
        else:
            self._cache = {}

    def verdict(self, ep: dict[str, Any]) -> bool:
        return self._cache.get(ep["episode_id"], False)

    def observed_features(self) -> frozenset[str]:
        return frozenset({"actions", "expected_actions", "violations_by_type"})
